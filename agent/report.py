"""Input (alert) and output (RCA report) of an investigation."""

import json
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, Field


class Alert(BaseModel):
    """The alert to investigate, as received from Prometheus/Alertmanager."""

    name: str
    labels: dict[str, str] = Field(default_factory=dict)
    annotations: dict[str, str] = Field(default_factory=dict)


class RootCauseCategory(str, Enum):
    """A fixed set of categories makes evaluation deterministic: the expected
    category of a test scenario can be compared with ==, no fuzzy text matching."""

    service_down = "service_down"
    sensor_anomaly = "sensor_anomaly"
    alert_storm = "alert_storm"
    unknown = "unknown"


class Evidence(BaseModel):
    tool: str
    query: str
    finding: str


class ModelReport(BaseModel):
    """The part of the report the LLM writes. Validated strictly, so a wrong
    category or a missing field is detected and the model is asked to fix it."""

    summary: str
    root_cause_category: RootCauseCategory
    root_cause_explanation: str
    evidence: list[Evidence]
    confidence: Literal["low", "medium", "high"]
    suggested_actions: list[str]


class RCAReport(ModelReport):
    """The final report: the model's findings plus facts the loop measured itself."""

    alert_name: str
    steps_used: int
    duration_seconds: float
    # Why the investigation ended: "completed", "max_steps", "timeout",
    # "invalid_output" or "llm_error". Anything but "completed" means the
    # report was generated by the loop, not by the model.
    stop_reason: str = "completed"


def parse_model_report(text: str) -> ModelReport:
    """Extract and validate the JSON report from the model's final answer.

    Models often wrap JSON in ```json fences or add a sentence around it,
    so the outermost {...} block is used. Raises ValueError if that fails.
    """
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end <= start:
        raise ValueError("no JSON object found in the answer")
    data: Any = json.loads(text[start : end + 1])
    return ModelReport.model_validate(data)
