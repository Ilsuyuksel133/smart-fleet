"""Measure how well search_runbook finds the right runbook section.

Usage (from the repository root, with Ollama running and nomic-embed-text pulled):

    python -m eval.run_retrieval_eval

Each question in eval/retrieval/questions.yaml names the section that answers it.
Both search methods rank the sections (best passage per section), and three
numbers are reported for each:

- hit@1: the right section is the first result
- hit@3: the right section is among the first three (search_runbook returns three)
- MRR:   mean of 1/rank of the right section (1.0 = always first, 0.5 = always second)

Results go to eval/retrieval/results.md.
"""

import argparse
import os
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import yaml

from agent.config import Settings
from agent.rag import Embedder, FakeEmbedder, OllamaEmbedder, RunbookSearch

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS = ROOT / "eval" / "retrieval" / "questions.yaml"
# Cached vectors of the evaluation, separate from the agent's own index
INDEX_PATH = ROOT / "eval" / "retrieval" / ".runbook_index.json"


@dataclass
class Question:
    question: str
    expected: str  # prefix of the section title, e.g. "FleetApiDown"


@dataclass
class Ranked:
    question: Question
    sections: list[str]  # best first, each section once

    @property
    def rank(self) -> int | None:
        """1-based rank of the expected section, None if it was not returned at all."""
        for position, section in enumerate(self.sections, start=1):
            if section.startswith(self.question.expected):
                return position
        return None


def load_questions(path: Path = QUESTIONS) -> list[Question]:
    return [Question(**item) for item in yaml.safe_load(path.read_text(encoding="utf-8"))]


def rank_sections(search: RunbookSearch, question: str, method: str) -> list[str]:
    """All sections, ordered by their best passage for this question."""
    every_chunk = len(search.chunks) or 1000
    if method == "keyword":
        result = search.keyword_search(question, every_chunk)
    else:
        result = search.search(question, every_chunk)
        if result.method != "embedding":
            raise RuntimeError(f"embedding search failed: {result.note}")
    return list(dict.fromkeys(chunk.section for chunk, _ in result.hits))


def metrics(ranked: list[Ranked]) -> dict[str, float]:
    ranks = [r.rank for r in ranked]
    count = len(ranks)
    return {
        "hit@1": sum(1 for rank in ranks if rank == 1) / count,
        "hit@3": sum(1 for rank in ranks if rank is not None and rank <= 3) / count,
        "mrr": sum(1 / rank for rank in ranks if rank) / count,
    }


def evaluate(search: RunbookSearch, questions: list[Question]) -> dict[str, list[Ranked]]:
    search.warm_up()
    return {
        method: [Ranked(q, rank_sections(search, q.question, method)) for q in questions]
        for method in ("embedding", "keyword")
    }


def render_markdown(results: dict[str, list[Ranked]], metadata: dict[str, str]) -> str:
    lines = [
        "# Runbook retrieval evaluation",
        "",
        f"Generated by `python -m eval.run_retrieval_eval` on {metadata['date']}. "
        f"Embedder: `{metadata['embedder']}`, chunks: {metadata['chunks']} "
        f"(max {metadata['chunk_chars']} characters), questions: {metadata['questions']}.",
        "",
        "| Method | hit@1 | hit@3 | MRR |",
        "|---|---|---|---|",
    ]
    for method, ranked in results.items():
        m = metrics(ranked)
        lines.append(f"| {method} | {m['hit@1']:.0%} | {m['hit@3']:.0%} | {m['mrr']:.2f} |")

    lines += [
        "",
        "## Per question",
        "",
        "Rank of the expected section (– = not returned).",
        "",
        "| Question | Expected | Embedding | Keyword |",
        "|---|---|---|---|",
    ]
    for semantic, keyword in zip(results["embedding"], results["keyword"]):
        q = semantic.question
        lines.append(
            f"| {q.question} | {q.expected} | {semantic.rank or '–'} | {keyword.rank or '–'} |"
        )

    misses = [r for r in results["embedding"] if r.rank != 1]
    if misses:
        lines += ["", "## Embedding search: questions not answered first", ""]
        for r in misses:
            lines.append(
                f"- *{r.question.question}* → expected **{r.question.expected}**, "
                f"got {', '.join(r.sections[:3])}"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ollama-url", default=os.getenv("OLLAMA_URL", "http://localhost:11434"))
    parser.add_argument("--model", default="nomic-embed-text")
    parser.add_argument("--fake", action="store_true", help="FakeEmbedder instead of Ollama")
    parser.add_argument("--output", type=Path, default=ROOT / "eval" / "retrieval" / "results.md")
    args = parser.parse_args()

    settings = Settings(
        runbook_index_path=INDEX_PATH,
        runbook_path=ROOT / "docs" / "RUNBOOK.md",
    )
    embedder: Embedder = (
        FakeEmbedder() if args.fake else OllamaEmbedder(args.ollama_url, args.model, timeout=60)
    )
    search = RunbookSearch(settings, embedder)
    questions = load_questions()
    results = evaluate(search, questions)
    metadata = {
        "date": datetime.now(UTC).strftime("%Y-%m-%d"),
        "embedder": embedder.name,
        "chunks": str(len(search.chunks)),
        "chunk_chars": str(settings.rag_chunk_chars),
        "questions": str(len(questions)),
    }
    args.output.write_text(render_markdown(results, metadata), encoding="utf-8")
    for method, ranked in results.items():
        m = metrics(ranked)
        print(f"{method:9s} hit@1={m['hit@1']:.0%} hit@3={m['hit@3']:.0%} MRR={m['mrr']:.2f}")
    print(f"Written to {args.output}")


if __name__ == "__main__":  # pragma: no cover
    main()
